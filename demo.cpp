#include <stdio.h>

int main() {
    int num1, num2;

    // Sample Input
    printf("Enter first number: ");
    scanf("%d", &num1);

    printf("Enter second number: ");
    scanf("%d", &num2);

    // Expected Output
    printf("First Number: %d\n", num1);
    printf("Second Number: %d\n", num2);

    return 0;
}
