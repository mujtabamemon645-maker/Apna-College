#include <stdio.h>

int main() {
    // Printing text with newline formatting
    printf("Welcome to C Programming\n\n");
    
    // Printing student info layout
    printf("Name:\tAli\n");
    printf("Age:\t20\n");
    printf("Grade:\tA\n\n");
    
    // Using \\ to successfully print backslashes in a file path
    printf("File Path: C:\\Users\\Student\n\n");
    
    // Using \" to successfully print actual double quotes
    printf("He said: \"Hello\"\n");

    return 0;
}